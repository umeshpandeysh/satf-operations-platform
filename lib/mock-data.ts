/**
 * Compute dashboard metrics from the mock tour dataset.
 * All calculations are based on the DEMO_TODAY baseline.
 */
export function computeDashboardMetrics(): DashboardMetrics {
  const today = DEMO_TODAY;

  const arrivalsToday = MOCK_TOURS.filter(
    (t) => t.arrivalDate === today && t.status !== "cancelled"
  ).length;

  const departuresToday = MOCK_TOURS.filter(
    (t) => t.departureDate === today && t.status !== "cancelled"
  ).length;

  const activeToday = MOCK_TOURS.filter(
    (t) =>
      t.status === "active" &&
      t.arrivalDate <= today &&
      t.departureDate >= today
  ).length;

  const requireAttention = MOCK_TOURS.filter(
    (t) => t.status === "attention"
  ).length;

  return { arrivalsToday, departuresToday, activeToday, requireAttention };
}

/**
 * Derive attention items — tours that need immediate action.
 */
export function getAttentionItems(): AttentionItem[] {
  return MOCK_TOURS.filter((t) => t.status === "attention").map((t) => ({
    tourId: t.id,
    bookingReference: t.bookingReference,
    groupName: t.group.groupName,
    reason: t.operationalNotes ?? "Requires attention — see tour record.",
  }));
}

/**
 * Tours arriving within the next N days from DEMO_TODAY.
 */
export function getUpcomingArrivals(days = 7): Tour[] {
  const from = new Date(DEMO_TODAY);
  const to = new Date(DEMO_TODAY);
  to.setDate(to.getDate() + days);

  return MOCK_TOURS.filter((t) => {
    const d = new Date(t.arrivalDate);
    return d >= from && d <= to && t.status !== "cancelled" && t.status !== "completed";
  }).sort((a, b) => a.arrivalDate.localeCompare(b.arrivalDate));
}
